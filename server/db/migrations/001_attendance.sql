CREATE INDEX IF NOT EXISTS idx_attendance_connect_card  ON attendance (connect_card_id);
CREATE INDEX IF NOT EXISTS idx_attendance_week          ON attendance (week_start);
CREATE INDEX IF NOT EXISTS idx_attendance_ministry      ON attendance (ministry_id);
